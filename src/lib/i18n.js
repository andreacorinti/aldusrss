export function resolveLanguage() {
  try {
    const nav = (navigator.language || "").slice(0, 2).toLowerCase();
    return nav === "it" ? "it" : "en";
  } catch {
    return "it";
  }
}

export function t(lang, key) {
  return STRINGS[lang]?.[key] ?? STRINGS.it[key] ?? key;
}
